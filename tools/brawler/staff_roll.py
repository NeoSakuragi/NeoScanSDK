#!/usr/bin/env python3
"""The ending's staff roll as sprites (main.c "the ending", EN_STAFF; Bruno 2026-10-11 note 20261006-173249-5d29: "do a
pixel-by-pixel scrolling"). The fix layer moves only in 8 px rows, so the roll is drawn by SR_COLS sprites side by side
(16 px columns, x 0-319), moved a pixel at a time.

game.json ending.staff.lines (validated by build_tables.py ending_tables) laid out exactly as the fix roll had them: a
line a fix row (8 px), centred on column 20 - (n + 1) / 2, '^' = a heading; each character = the S ROM font's glyph
(build/font.s1, tile = its ASCII code: Kizuna's font, make_hud.py), its pens kept (1 white, 2-5 the gradient, 14 the
shadow; 0 transparent over the black backdrop), a heading's gradient moved to pens 6-9 (main.c loads fix palette 1's
highlighted colours there): one sprite palette for the whole roll. The picture (320 x lines * 8 px) is cut into 16 x 16
tiles, the blank ones = 0 (C ROM tile 0, empty), identical ones stored once, appended to the C ROM after the big
portraits (rom_c1/c2.bin).

    python3 staff_roll.py GAME.json BUILD_DIR   -> BUILD_DIR/rom_c1/c2.bin (+ the roll's tiles), BUILD_DIR/staff_roll.h"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(HERE, '..'))
import numpy as np
from make_hud import sdecode
from build_tables import END_COLS
from tile_encoder import encode_crom_tile

SR_COLS = 20                                   # sprites: 320 / 16
HILITE = 4                                     # a heading's gradient pens 2-5 -> 6-9


def build(game_json, build_dir):
    lines = json.load(open(game_json))['ending']['staff']['lines']
    font = open(os.path.join(build_dir, 'font.s1'), 'rb').read()
    rows = (len(lines) * 8 + 15) // 16
    pic = np.zeros((rows * 16, SR_COLS * 16), np.uint8)
    for k, t in enumerate(lines):
        head = t.startswith('^'); t = t.lstrip('^')
        assert len(t) <= END_COLS and all(0x20 <= ord(ch) < 0x7F for ch in t), f'staff line {t!r}'
        c0 = 20 - ((len(t) + 1) >> 1)              # the fix roll's centring (main.c staff_draw until 0.10.51)
        for i, ch in enumerate(t):
            g = np.array(sdecode(font[ord(ch) * 32:ord(ch) * 32 + 32]), np.uint8)
            if head: g = np.where((g >= 2) & (g <= 5), g + HILITE, g)
            pic[k * 8:k * 8 + 8, (c0 + i) * 8:(c0 + i) * 8 + 8] = g
    c1p, c2p = os.path.join(build_dir, 'rom_c1.bin'), os.path.join(build_dir, 'rom_c2.bin')
    c1, c2 = bytearray(open(c1p, 'rb').read()), bytearray(open(c2p, 'rb').read())
    assert not any(c1[:64]) and not any(c2[:64]), 'C ROM tile 0 is not empty'
    base = len(c1) // 64
    index, smap = {}, []
    for r in range(rows):
        for c in range(SR_COLS):
            px = pic[r * 16:r * 16 + 16, c * 16:c * 16 + 16]
            if not px.any(): smap.append(0); continue
            key = px.tobytes()
            if key not in index:
                index[key] = len(index) + 1
                a, b = encode_crom_tile(px); c1.extend(a); c2.extend(b)
            smap.append(index[key])
    open(c1p, 'wb').write(bytes(c1)); open(c2p, 'wb').write(bytes(c2))
    h = ['/* Generated by tools/brawler/staff_roll.py from game.json ending.staff.lines. Do not edit. */',
         '#ifndef STAFF_ROLL_H', '#define STAFF_ROLL_H',
         f'#define SR_COLS {SR_COLS}   /* sprites side by side, 16 px each */',
         f'#define SR_ROWS {rows}   /* tile rows: the roll is SR_ROWS * 16 px high (line k at y 8 k) */',
         f'#define SR_TILE0 0x{base - 1:X}UL   /* + a map entry = its C ROM tile */',
         f'static const uint16_t sr_map[SR_ROWS * SR_COLS] = {{   /* row-major; 0 = blank (tile 0) */',
         ',\n'.join('    ' + ', '.join(str(v) for v in smap[r * SR_COLS:(r + 1) * SR_COLS]) for r in range(rows)),
         '};', '#endif']
    open(os.path.join(build_dir, 'staff_roll.h'), 'w').write('\n'.join(h) + '\n')
    print(f'staff roll: {len(lines)} lines, {rows} x {SR_COLS} tiles, {len(index)} stored from {base} '
          f'({len(index) * 128 // 1024} KB), C ROM {2 * len(c1) / 1048576:.2f} MB')


if __name__ == '__main__':
    if len(sys.argv) != 3: sys.exit(__doc__)
    build(sys.argv[1], sys.argv[2])
